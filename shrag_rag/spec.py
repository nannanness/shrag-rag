# -*- coding: utf-8 -*-
"""全项目共享的「指标口径」与文本工具。

## 为什么必须单独抽出来

验证层（``parse/verify.py``）和抽取层（``extract/metrics.py``）都要用同一套
指标定义。**原先两处各维护一份，结果分叉了**：

- 抽取层已经把「归母净利润」与「净利润（含少数股东损益）」拆成两个独立指标
- 验证层还在用合并的定义，于是继续拿"归母"去比"全部"

后果是 100 份里报出 **89 个 WARN**，绝大多数是假警报。假警报比不检查更糟 ——
会让人不再信任检查结果，也会掩盖真实问题。

## 为什么放在顶层而不是 extract/ 里

``parse`` 是底层，``extract`` 建立在它之上。若让 ``parse/verify.py`` 反过来
import ``extract``，就形成了分层倒置。所以共享定义放在中性位置，两边都依赖它：

    spec.py          ← 纯定义，不依赖包内任何东西
      ↑        ↑
    parse/    extract/
"""

from __future__ import annotations

import re

# --------------------------------------------------------------------------- #
# 文本工具
# --------------------------------------------------------------------------- #

_NUM = re.compile(r"^-?\d[\d,]*(\.\d+)?$")
_UNITS = {"元", "千元", "万元", "百万元", "亿元", "人民币", "币种", "元/股", "万股"}

# 行标签前缀，匹配前先剥掉（"其中：营业收入" 应视为 "营业收入"）
LABEL_PREFIX = ("其中：", "其中:", "减：", "减:", "加：", "加:", "其中", "减", "加")

# 行首的**中文/阿拉伯序号**。财报报表里的行标签几乎都带序号：
#   「一、营业收入」「三、利润总额」「（一）营业收入」「1、货币资金」「①货币资金」
# 不剥掉的话这些行永远匹配不上 —— 实测 600004 的合并利润表就被漏掉，
# 交叉验证退化到拿母公司报表去比，报出假的"不一致"。
#
# 注意：阿拉伯数字**必须带分隔符**（`1、` `1.`），否则会把
# 「1年以内」这类账龄行的前导数字也吃掉。
_ENUM_RE = re.compile(
    r"^(?:"
    r"[\(（]\s*[0-9一二三四五六七八九十]+\s*[\)）]"     # （一）  (1)
    r"|[0-9]+\s*[、.．]"                              # 1、  1.
    r"|[一二三四五六七八九十]+\s*[、.．]"               # 一、  三.
    r"|[①-⑳]"                                        # ①
    r")\s*"
)

# 公开别名：切片层需要用它判断"剥掉序号后还剩什么"，以区分标题与正文句子
ENUM_RE = _ENUM_RE

YEAR_RE = re.compile(r"((?:19|20)\d{2})\s*年")


def norm_label(s: str) -> str:
    """规范化行标签：剥掉行首序号与「其中：」这类前缀。"""
    t = _ENUM_RE.sub("", (s or "").strip())
    t = t.replace(" ", "").replace("\u3000", "")
    for p in LABEL_PREFIX:
        if t.startswith(p) and len(t) > len(p):
            return t[len(p):]
    return t


def parse_number(s: str) -> float | None:
    """解析表格里的数字单元格。支持 ``(1,234)`` 负数写法与全角括号。"""
    t = (s or "").strip().replace(",", "").replace("，", "")
    t = t.replace("（", "(").replace("）", ")")
    if not t:
        return None
    neg = t.startswith("(") and t.endswith(")")
    t = t.strip("()")
    if not t or t in _UNITS:
        return None
    if not _NUM.match(t):
        return None
    try:
        v = float(t)
    except ValueError:
        return None
    return -v if neg else v


def is_year_header_cell(text: str) -> int | None:
    """表头单元格里若含年份则返回该年，否则 None。

    会排除「本期比上年同期增减(%)」这类含百分号/增减字样的单元格。
    """
    t = (text or "").strip()
    if not t or "增减" in t or "变动" in t or "%" in t or "％" in t:
        return None
    m = YEAR_RE.search(t)
    return int(m.group(1)) if m else None


